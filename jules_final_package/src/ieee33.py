#!/usr/bin/env python3
"""IEEE 33-bus radial feeder (Baran & Wu, 1989). Base 12.66 kV, 10 MVA."""
from __future__ import annotations
import numpy as np

VBASE_KV = 12.66
SBASE_MVA = 10.0
ZBASE = VBASE_KV**2 / SBASE_MVA  # ohm

# from, to, r_ohm, x_ohm  (32 branches)
BRANCHES = np.array([
    [1, 2, 0.0922, 0.0470], [2, 3, 0.4930, 0.2511], [3, 4, 0.3660, 0.1864],
    [4, 5, 0.3811, 0.1941], [5, 6, 0.8190, 0.7070], [6, 7, 0.1872, 0.6188],
    [7, 8, 1.7114, 1.2351], [8, 9, 1.0300, 0.7400], [9, 10, 1.0440, 0.7400],
    [10, 11, 0.1966, 0.0650], [11, 12, 0.3744, 0.1238], [12, 13, 1.4680, 1.1550],
    [13, 14, 0.5416, 0.7129], [14, 15, 0.5910, 0.5260], [15, 16, 0.7463, 0.5450],
    [16, 17, 1.2890, 1.7210], [17, 18, 0.7320, 0.5740], [2, 19, 0.1640, 0.1565],
    [19, 20, 1.5042, 1.3554], [20, 21, 0.4095, 0.4784], [21, 22, 0.7089, 0.9373],
    [3, 23, 0.4512, 0.3083], [23, 24, 0.8980, 0.7091], [24, 25, 0.8960, 0.7011],
    [6, 26, 0.2030, 0.1034], [26, 27, 0.2842, 0.1447], [27, 28, 1.0590, 0.9337],
    [28, 29, 0.8042, 0.7006], [29, 30, 0.5075, 0.2585], [30, 31, 0.9744, 0.9630],
    [31, 32, 0.3105, 0.3619], [32, 33, 0.3410, 0.5302],
], dtype=float)

# bus 2..33 peak load kW, kvar (bus 1 slack)
LOAD_KW = np.array([
    100, 90, 120, 60, 60, 200, 200, 60, 60, 45, 60, 60, 120, 60, 60, 60, 90,
    90, 90, 90, 90, 90, 420, 420, 60, 60, 60, 120, 200, 150, 210, 60,
], dtype=float)
LOAD_KVAR = np.array([
    60, 40, 80, 30, 20, 100, 100, 20, 20, 30, 35, 35, 80, 10, 20, 20, 40,
    40, 40, 40, 40, 50, 200, 200, 25, 25, 20, 70, 600, 70, 100, 40,
], dtype=float)


def pu_branch():
    r = BRANCHES[:, 2] / ZBASE
    x = BRANCHES[:, 3] / ZBASE
    fr = BRANCHES[:, 0].astype(int) - 1
    to = BRANCHES[:, 1].astype(int) - 1
    return fr, to, r, x


def peak_load_mw():
    p = np.zeros(33)
    q = np.zeros(33)
    p[1:] = LOAD_KW / 1000.0
    q[1:] = LOAD_KVAR / 1000.0
    return p, q
